# frozen_string_literal: true

require "isolation/abstract_unit"
require "open3"

class HelpTest < ActiveSupport::TestCase
  include ActiveSupport::Testing::Isolation

  def setup
    build_app
  end

  def teardown
    teardown_app
  end

  test "lists common commands and extended commands with descriptions" do
    output = rails("help")
    assert_match "You must specify a command. The most common commands are:", output
    assert_match "  generate     Generate new code (short-cut alias: \"g\")", output
    assert_match "In addition to those commands", output
    assert_match(/^about(\s+)List versions of all Rails frameworks/, output)
    assert_match(/^test:models(\s+)Run tests in test\/models/, output)
    assert_match(/^routes(\s+)List all the defined routes/, output)
    assert_no_match(/^generate/, output)
    assert_no_match(/^console/, output)
    assert_no_match(/^server/, output)
  end

  test "short-cut alias works" do
    output = rails("-h")
    assert_match "You must specify a command. The most common commands are:", output
    assert_match "  generate     Generate new code (short-cut alias: \"g\")", output
    assert_match "In addition to those commands", output
  end

  test "when no arguments are passed lists the common commands only" do
    output = rails("")
    assert_match "You must specify a command. The most common commands are:", output
    assert_match "  generate     Generate new code (short-cut alias: \"g\")", output
    assert_no_match "In addition to those commands", output
  end

  test "outside application root it lists gem commands" do
    output = gem_rails("")
    assert_match "You must specify a command:", output
    assert_match "  new          Create a new Rails application.", output
  end

  test "outside application root unrecognized commands print usage and exit with a failure status" do
    ["some-invalid-argument", "db:migrate", "server"].each do |cmd|
      output, status = gem_rails_with_status(cmd)
      assert_not_predicate status, :success?, "Expected `rails #{cmd}` to exit with a failure status"
      assert_match "rails new APP_PATH [options]", output
    end
  end

  test "outside application root unrecognized commands only print usage" do
    Dir.mktmpdir do |dir|
      output, status = gem_rails_with_status("-- new blog --skip-bundle --skip-git", chdir: dir)

      assert_not_predicate status, :success?
      assert_match "rails new APP_PATH [options]", output
      assert_not File.exist?(File.join(dir, "blog")), "Expected no application to be generated"
    end
  end

  test "outside application root known commands exit successfully" do
    {
      "" => "You must specify a command:",
      "-h" => "You must specify a command:",
      "-?" => "You must specify a command:",
      "--help" => "You must specify a command:",
      "help" => "You must specify a command:",
      "-v" => "Rails #{Rails::VERSION::STRING}",
      "--version" => "Rails #{Rails::VERSION::STRING}",
      "new --help" => "rails new APP_PATH [options]",
      "plugin --help" => "rails plugin new APP_PATH [options]",
    }.each do |cmd, expected_output|
      output, status = gem_rails_with_status(cmd)
      assert_predicate status, :success?, "Expected `rails #{cmd}` to exit successfully"
      assert_match expected_output, output
    end
  end

  test "with a Bundler-generated bin/rails the command runs without falling through to the gem usage" do
    File.write("#{app_path}/bin/rails", "# This file was generated by Bundler\n")

    output, status = gem_rails_with_status("runner 'puts \"RUNNER_OK\"'", chdir: app_path)

    assert_predicate status, :success?, output
    assert_match "RUNNER_OK", output
    assert_no_match "rails new APP_PATH [options]", output
  end

  private
    def gem_rails(cmd)
      capture(:stdout) do
        system("#{Gem.ruby} #{RAILS_FRAMEWORK_ROOT}/railties/exe/rails #{cmd}", exception: true)
      end
    end

    def gem_rails_with_status(cmd, chdir: Dir.pwd)
      Open3.capture2e("#{Gem.ruby} #{RAILS_FRAMEWORK_ROOT}/railties/exe/rails #{cmd}", chdir: chdir)
    end
end
